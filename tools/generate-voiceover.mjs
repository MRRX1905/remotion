// Generates the Indonesian voice-over for the motivational video.
//
// Why one file per line instead of a single long recording: every narration line
// becomes its own audio file with a known exact duration, so the composition can
// place each line on the timeline frame-accurately and derive captions from the
// very same data. No forced alignment or transcription step is needed.
//
// Usage:  node tools/generate-voiceover.mjs          (skips files that already exist)
//         FORCE=1 node tools/generate-voiceover.mjs  (regenerate everything)
//
// Outputs: public/voiceover/<id>.mp3   audio files consumed by <Audio>
//          src/voiceover-data.ts       timing + caption text imported by the composition

import {execFileSync} from "node:child_process";
import {existsSync, mkdirSync, readFileSync, writeFileSync} from "node:fs";
import path from "node:path";
import {fileURLToPath} from "node:url";

const rewind = (p) => path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", p);

const FPS = 30;
const LEAD_IN_FRAMES = 42; // let the title animate in before the narrator speaks
const GAP_FRAMES = 18; // breathing room between lines
const TAIL_FRAMES = 75; // outro hold after the last line

const config = JSON.parse(readFileSync(rewind("tools/voiceover-lines.json"), "utf8"));
const audioDir = rewind("public/voiceover");
mkdirSync(audioDir, {recursive: true});

const run = (cmd, args, opts = {}) => execFileSync(cmd, args, {encoding: "utf8", ...opts}).trim();

const probeDuration = (file) =>
  Number.parseFloat(
    run("ffprobe", ["-v", "error", "-show_entries", "format=duration", "-of", "default=nw=1:nk=1", file]),
  );

if (!existsSync(rewind("node_modules/remotion"))) {
  throw new Error("Run `npm install` first — node_modules/remotion is missing.");
}

const lines = [];
let cursor = LEAD_IN_FRAMES;

for (const line of config.lines) {
  const audioPath = path.join(audioDir, `${line.id}.mp3`);

  if (process.env.FORCE === "1" || !existsSync(audioPath)) {
    console.log(`synthesising ${line.id} …`);
    run("python", [
      "-m", "edge_tts",
      "--voice", config.voice,
      "--rate", config.rate,
      "--pitch", config.pitch,
      "--text", line.text,
      "--write-media", audioPath,
    ]);
  } else {
    console.log(`reusing     ${line.id}`);
  }

  const seconds = probeDuration(audioPath);
  if (!Number.isFinite(seconds) || seconds <= 0) {
    throw new Error(`ffprobe could not read a duration for ${audioPath}`);
  }

  const durationInFrames = Math.ceil(seconds * FPS);
  lines.push({
    id: line.id,
    kicker: line.kicker,
    text: line.text,
    headline: line.headline,
    emphasis: line.emphasis,
    audioSrc: `voiceover/${line.id}.mp3`,
    durationInSeconds: Number(seconds.toFixed(3)),
    durationInFrames,
    startFrame: cursor,
  });

  cursor += durationInFrames + GAP_FRAMES;
}

const totalDurationInFrames = cursor - GAP_FRAMES + TAIL_FRAMES;

const body = lines
  .map(
    (l) => `  {
    id: ${JSON.stringify(l.id)},
    kicker: ${JSON.stringify(l.kicker)},
    text: ${JSON.stringify(l.text)},
    headline: ${JSON.stringify(l.headline)},
    emphasis: ${JSON.stringify(l.emphasis)},
    audioSrc: ${JSON.stringify(l.audioSrc)},
    durationInSeconds: ${l.durationInSeconds},
    durationInFrames: ${l.durationInFrames},
    startFrame: ${l.startFrame},
  },`,
  )
  .join("\n");

writeFileSync(
  rewind("src/voiceover-data.ts"),
  `// AUTO-GENERATED by tools/generate-voiceover.mjs — do not edit by hand.
// Regenerate with: node tools/generate-voiceover.mjs

export const FPS = ${FPS};
export const LEAD_IN_FRAMES = ${LEAD_IN_FRAMES};
export const GAP_FRAMES = ${GAP_FRAMES};
export const TAIL_FRAMES = ${TAIL_FRAMES};
export const TOTAL_DURATION_IN_FRAMES = ${totalDurationInFrames};

export type VoiceoverLine = {
  id: string;
  kicker: string;
  text: string;
  headline: string[];
  emphasis: string;
  audioSrc: string;
  durationInSeconds: number;
  durationInFrames: number;
  startFrame: number;
};

export const VOICEOVER: VoiceoverLine[] = [
${body}
];
`,
);

const totalSeconds = (totalDurationInFrames / FPS).toFixed(1);
console.log(`\n${lines.length} lines → ${totalDurationInFrames} frames @ ${FPS}fps (${totalSeconds}s)`);
for (const l of lines) {
  console.log(`  ${l.kicker}  @${String(l.startFrame).padStart(5)}f  ${l.durationInSeconds.toFixed(2)}s  ${l.text.slice(0, 44)}…`);
}
